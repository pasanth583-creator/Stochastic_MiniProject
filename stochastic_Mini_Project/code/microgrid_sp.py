"""
microgrid_sp.py
===============
Two-stage stochastic program (with a CVaR risk-averse variant) for the
day-ahead energy-procurement problem of a campus solar + battery microgrid.

Course : 21AIE321T - Stochastic Decision Making (CLA-2, Assignment IV)

Stage 1 (here-and-now, before uncertainty is revealed):
    x_t  = day-ahead grid purchase commitment for hour t   [kWh]
Stage 2 (recourse, after solar S_t and demand D_t are revealed):
    c_t  battery charge, d_t battery discharge,
    g_t  real-time (imbalance) purchase, e_t surplus export, b_t battery state of charge.

All monetary values are in INR.  Solar and demand scenarios are SYNTHETIC
(generated by `gen_scenarios`) -- see the report for the assumptions.
"""
from dataclasses import dataclass, replace
import numpy as np
import scipy.sparse as sp
from scipy.optimize import linprog


# --------------------------------------------------------------------------
# 1. Parameters
# --------------------------------------------------------------------------
@dataclass(frozen=True)
class Params:
    T: int = 24
    # --- assets ---
    solar_kwp: float = 800.0       # PV plant size
    batt_kwh: float = 1000.0       # battery energy capacity
    batt_kw: float = 250.0         # battery power limit (charge / discharge)
    eta: float = 0.92              # one-way efficiency (round trip = eta^2)
    soc_min_frac: float = 0.10     # minimum state of charge (fraction of capacity)
    soc0_frac: float = 0.50        # initial SoC; terminal SoC must be >= initial
    deg_cost: float = 1.0          # INR per kWh discharged (battery wear)
    x_max: float = 1000.0          # contract-demand limit on day-ahead purchase [kW]
    # --- prices (INR / kWh) ---
    export_price: float = 3.0      # price received for surplus power
    rt_premium: float = 1.6        # real-time price = rt_premium * day-ahead price
    # --- weather mixture ---
    p_over: float = 0.25           # P(overcast / monsoon day)
    # --- demand ---
    p_weekend: float = 2.0 / 7.0   # P(holiday-type, low-load day)
    weekend_factor: float = 0.72

    @property
    def pda(self):
        """Day-ahead time-of-day tariff (INR/kWh), 24 values."""
        p = np.empty(24)
        for h in range(24):
            if h < 6 or h >= 22:
                p[h] = 5.5          # night / off-peak
            elif h < 9:
                p[h] = 6.5          # morning shoulder
            elif h < 18:
                p[h] = 6.0          # solar hours
            else:
                p[h] = 9.0          # evening peak 18-22
        return p

    @property
    def prt(self):
        return self.pda * self.rt_premium


# Base campus load profile (kW) for a normal working day
BASE_LOAD = np.array([250, 245, 240, 240, 245, 255, 300, 380, 520, 650, 700, 715,
                      720, 715, 710, 700, 650, 600, 580, 600, 600, 550, 400, 300],
                     dtype=float)


def clear_sky_shape():
    h = np.arange(24) + 0.5
    return 0.88 * np.maximum(0.0, np.sin(np.pi * (h - 6.0) / 12.0)) ** 1.15


# --------------------------------------------------------------------------
# 2. Scenario generator (synthetic, calibrated by assumption)
# --------------------------------------------------------------------------
def gen_scenarios(N, seed, P: Params):
    """Return S (N,24) solar [kW] and D (N,24) demand [kW]."""
    rng = np.random.default_rng(seed)
    pc = (1 - P.p_over) * 35.0 / 75.0
    pp = (1 - P.p_over) * 40.0 / 75.0
    probs = np.array([pc, pp, P.p_over])
    mu_type = np.array([0.92, 0.62, 0.28])
    sd_type = np.array([0.03, 0.18, 0.08])
    rho = 0.8

    cs = clear_sky_shape()
    S = np.zeros((N, 24))
    D = np.zeros((N, 24))
    for n in range(N):
        k = rng.choice(3, p=probs)
        mu_day = np.clip(mu_type[k] + rng.normal(0, 0.05), 0.05, 1.0)
        noise = np.zeros(24)
        e = rng.normal(size=24)
        for t in range(24):
            prev = noise[t - 1] if t > 0 else 0.0
            noise[t] = rho * prev + np.sqrt(1 - rho ** 2) * sd_type[k] * e[t]
        kt = np.clip(mu_day + noise, 0.02, 1.0)
        S[n] = P.solar_kwp * cs * kt

        weekend = rng.random() < P.p_weekend
        day_f = np.exp(rng.normal(0, 0.08)) * (P.weekend_factor if weekend else 1.0)
        z = np.zeros(24)
        ez = rng.normal(size=24)
        for t in range(24):
            prev = z[t - 1] if t > 0 else 0.0
            z[t] = 0.7 * prev + np.sqrt(1 - 0.49) * 0.05 * ez[t]
        D[n] = BASE_LOAD * day_f * np.exp(z)
    return S, D


# --------------------------------------------------------------------------
# 3. Extensive-form LP
# --------------------------------------------------------------------------
NV = 5  # per-scenario variable groups: c, d, b, g, e  (each length T)


def _solve(S, D, P: Params, x_fixed=None, lam=0.0, alpha=0.9):
    N, T = S.shape
    nvs = NV * T
    n_base = T + N * nvs
    nv = n_base + ((1 + N) if lam > 0 else 0)
    pda, prt, pex, deg, eta = P.pda, P.prt, P.export_price, P.deg_cost, P.eta
    cap = P.batt_kwh
    Pb = P.batt_kw if cap > 0 else 0.0
    bmin, bmax, b0 = P.soc_min_frac * cap, cap, P.soc0_frac * cap

    def off(s):
        return T + s * nvs

    # ---------- objective ----------
    cost = np.zeros(nv)
    cost[:T] = pda
    w = (1.0 - lam) / N
    for s in range(N):
        o = off(s)
        cost[o + 3 * T:o + 4 * T] = w * prt        # g
        cost[o + 4 * T:o + 5 * T] = -w * pex       # e
        cost[o + 1 * T:o + 2 * T] = w * deg        # d
    if lam > 0:
        i_eta = n_base
        cost[i_eta] = lam
        cost[i_eta + 1:] = lam / ((1 - alpha) * N)

    # ---------- bounds ----------
    lb = np.zeros(nv)
    ub = np.full(nv, np.inf)
    ub[:T] = P.x_max
    if x_fixed is not None:
        lb[:T] = x_fixed
        ub[:T] = x_fixed
    for s in range(N):
        o = off(s)
        ub[o:o + T] = Pb                       # c
        ub[o + T:o + 2 * T] = Pb               # d
        lb[o + 2 * T:o + 3 * T] = bmin         # b
        ub[o + 2 * T:o + 3 * T] = bmax
        lb[o + 3 * T - 1] = b0                 # terminal SoC >= initial
    if lam > 0:
        lb[n_base] = -np.inf
        ub[n_base] = np.inf

    # ---------- equality constraints ----------
    rows, cols, vals, rhs = [], [], [], []
    t_idx = np.arange(T)
    for s in range(N):
        o = off(s)
        r0 = s * 2 * T
        # energy balance: x + d + g - c - e = D - S
        for (col, v) in ((t_idx, 1.0), (o + T + t_idx, 1.0), (o + 3 * T + t_idx, 1.0),
                         (o + t_idx, -1.0), (o + 4 * T + t_idx, -1.0)):
            rows.append(r0 + t_idx); cols.append(col); vals.append(np.full(T, v))
        rhs.append(D[s] - S[s])
        # SoC: b_t - b_{t-1} - eta c_t + d_t/eta = 0   (b_{-1} = b0 -> rhs)
        r1 = r0 + T
        rows.append(r1 + t_idx); cols.append(o + 2 * T + t_idx); vals.append(np.ones(T))
        rows.append(r1 + t_idx[1:]); cols.append(o + 2 * T + t_idx[:-1]); vals.append(-np.ones(T - 1))
        rows.append(r1 + t_idx); cols.append(o + t_idx); vals.append(np.full(T, -eta))
        rows.append(r1 + t_idx); cols.append(o + T + t_idx); vals.append(np.full(T, 1.0 / eta))
        r = np.zeros(T); r[0] = b0
        rhs.append(r)
    A_eq = sp.csr_matrix((np.concatenate(vals), (np.concatenate(rows), np.concatenate(cols))),
                         shape=(N * 2 * T, nv))
    b_eq = np.concatenate([np.concatenate([rhs[2 * s], rhs[2 * s + 1]]) for s in range(N)])

    # ---------- CVaR constraints:  sec_s - eta_var - u_s <= 0 ----------
    A_ub = b_ub = None
    if lam > 0:
        r_, c_, v_ = [], [], []
        for s in range(N):
            o = off(s)
            r_ += [np.full(T, s)] * 3
            c_ += [o + 3 * T + t_idx, o + 4 * T + t_idx, o + T + t_idx]
            v_ += [prt, -np.full(T, pex), np.full(T, deg)]
            r_.append(np.array([s])); c_.append(np.array([n_base])); v_.append(np.array([-1.0]))
            r_.append(np.array([s])); c_.append(np.array([n_base + 1 + s])); v_.append(np.array([-1.0]))
        A_ub = sp.csr_matrix((np.concatenate(v_), (np.concatenate(r_), np.concatenate(c_))), shape=(N, nv))
        b_ub = np.zeros(N)

    res = linprog(cost, A_ub=A_ub, b_ub=b_ub, A_eq=A_eq, b_eq=b_eq,
                  bounds=np.column_stack([lb, ub]), method="highs")
    if res.status != 0:
        raise RuntimeError(f"LP failed: {res.message}")
    z = res.x
    x = z[:T].copy()
    out = {"x": x, "obj": res.fun, "c": np.zeros((N, T)), "d": np.zeros((N, T)),
           "b": np.zeros((N, T)), "g": np.zeros((N, T)), "e": np.zeros((N, T))}
    for s in range(N):
        o = off(s)
        for j, key in enumerate(["c", "d", "b", "g", "e"]):
            out[key][s] = z[o + j * T:o + (j + 1) * T]
    sec = (out["g"] * prt - out["e"] * pex + out["d"] * deg).sum(axis=1)
    out["total_cost"] = float(pda @ x) + sec           # per-scenario total daily cost
    return out


# --------------------------------------------------------------------------
# 4. Public helpers
# --------------------------------------------------------------------------
def solve_sp(S, D, P, lam=0.0, alpha=0.9):
    """Risk-neutral (lam=0) or mean-CVaR two-stage SAA program. Returns dict."""
    return _solve(S, D, P, lam=lam, alpha=alpha)


def evaluate(x, S, D, P):
    """Per-scenario optimal recourse cost for a FIXED day-ahead plan x (one big LP)."""
    return _solve(S, D, P, x_fixed=x)["total_cost"]


def ev_plan(S, D, P):
    """Deterministic 'expected value' problem: replace S, D by their means."""
    return _solve(S.mean(0, keepdims=True), D.mean(0, keepdims=True), P)["x"]


def naive_plan(S, D, P):
    """Rule of thumb: buy forecast net load, ignore battery in planning."""
    return np.clip(D.mean(0) - S.mean(0), 0.0, P.x_max)


def wait_and_see(S, D, P):
    """Perfect-information cost: every scenario solved with its own x (hindsight)."""
    return np.array([_solve(S[i:i + 1], D[i:i + 1], P)["total_cost"][0] for i in range(len(S))])


def cvar(costs, alpha=0.9):
    q = np.quantile(costs, alpha)
    tail = costs[costs >= q]
    return float(tail.mean())
